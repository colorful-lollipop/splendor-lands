import { chromium } from 'playwright-core';
const CHROME = 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe';
const browser = await chromium.launch({ executablePath: CHROME, headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto('http://localhost:3001', { waitUntil: 'networkidle' });
await page.waitForTimeout(700);
await page.fill('#player-name', '启动验证');
await page.click('button:has-text("创建房间")');
await page.waitForSelector('.room-screen', { timeout: 15000 });
await page.click('.bot-add-group .btn:nth-child(2)');
await page.waitForTimeout(250);
await page.click('.bot-add-group .btn:nth-child(2)');
await page.waitForTimeout(400);
await page.screenshot({ path: 'shots/launch-room.png' });
await page.click('button:has-text("开始游戏")');
await page.waitForSelector('.game-shell', { timeout: 20000 });
await page.waitForTimeout(1800);
await page.screenshot({ path: 'shots/launch-game.png' });
console.log('errors', errs.slice(0, 3));
await browser.close();
